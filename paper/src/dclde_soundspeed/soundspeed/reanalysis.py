"""Full-depth sound-speed profiles from reanalysis, validated against in-situ.

OOI covers, at best, ~154-575 m of a 0-1575 m problem -- and only for the
25 Oct-15 Nov 2021 window; a tighter 1-6 Nov window covers only 216-575 m (see
`erddap.NOV_2021_STATUS`). So reanalysis is the base profile here and the
in-situ data is the validator, not the other way round. The disagreement over
whatever band actually overlaps is the uncertainty carried by every downstream
result, and it is measured here rather than assumed small. **The entire upper
water column above the validated band -- where every source sits and every ray
passes -- has no usable in-situ check at all; that is a limitation of this
research, not a detail (see `validation_summary`'s docstring).**

HYCOM GOFS 3.1 is the primary source: open NCSS subsetting, no account needed.
GLORYS12V1 would be better but needs a Copernicus Marine account and is
deliberately kept off the critical path. WOA23 monthly climatology would be an
independent cross-check but is not implemented here (out of scope for this
task's interfaces); if it is ever added, remember it is a climatological
November, not this November, and any result using it must say so.

HYCOM NCSS quirk (confirmed against the dataset's `.das` on 2026-09-17, not
guessed): `accept=csv` on this server returns the RAW packed Int16 values for
`water_temp` and `salinity`, not CF-unpacked physical values. Reading them
naively gives nonsense like a "temperature" of -6483 or a "salinity" of
12319. Both variables share `scale_factor=0.001`, `add_offset=20.0`,
`_FillValue=-30000`; `_unpack_hycom` undoes this before anything touches
`from_ts`. The vertical coordinate column is also not named "depth" -- it is
`vertCoord[unit="m"]` -- so column lookup matches on "vertcoord" first.

**Two committed profiles, two different roles -- do not conflate them.**

- `HYCOM_PROFILE_PATH` (key `hycom_oregon_nov` in `experiments.runner.PROFILES`)
  is fetched at the OOI mooring (44.37, -124.95), the *only* place this task
  can check HYCOM against a real measurement. That site is ~600 m deep on
  HYCOM's grid, so this profile only reaches ~600 m. It is the validation
  profile: use it to reproduce `profile_validation.csv`, not to run an
  experiment. Using it as an experiment's sound-speed model would silently
  clamp-extrapolate every pick deeper than ~600 m -- 30.8% of the real picks
  (3,428/11,117) -- exactly the Task 1 extrapolation failure mode,
  reintroduced through the data instead of the code.
- `HYCOM_EXPERIMENT_PROFILE_PATH` (key `hycom_south_deep`) is fetched at the
  South cable's own deepest channel (45.1492, -125.1081, cable depth -1575 m
  -- see `geometry.load_cables`), ~87 km from the OOI site and never checked
  against any in-situ measurement. HYCOM resolves real (non-fill) data there
  to 1500 m, leaving only the last ~75 m to the cable's -1575 m deepest
  channel as clamped extrapolation -- 1.64% of picks (182/11,117), versus
  30.8% for the validation-site profile. This is the profile experiments
  should use.

**The epistemics, stated plainly:** the experiment profile was never
validated. Its credibility is *inferred*, not measured -- HYCOM agreed with
in-situ to a median 0.47 m/s at a site 87 km away and ~1000 m shallower, and
that agreement is being extended, by assumption, to a different location and
to depths with no in-situ check anywhere along this coastline. That is the
best available evidence and a defensible choice, but it is not the same
claim as "this profile was checked against measurement." Anyone drawing a
conclusion from an experiment built on `hycom_south_deep` should carry that
distinction forward rather than cite the 0.47 m/s figure as if it applied
here.
"""

from __future__ import annotations

import io
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
import requests

from dclde_localization.physics.sound_speed_profile import SoundSpeedProfile

HYCOM_NCSS = "https://ncss.hycom.org/thredds/ncss/GLBy0.08/expt_93.0/ts3z"

# Where the committed, network-free HYCOM profiles live so
# experiments.runner.PROFILES can load them with no network at experiment
# time. Both are regenerated by paper/scripts/validate_hycom_profile.py,
# which is the actual fetch -- this module never fetches at import time.
#
# Resolved against this file's own location (Path(__file__)), not the process
# cwd: a cwd-relative Path silently means something different depending on
# where `uv run` (or a test collector, or a notebook) happens to be launched
# from, and this package is `pip install -e .`-installed specifically so it
# can be imported from outside the repo root. `_REPO_ROOT` walks up from
# .../paper/src/dclde_soundspeed/soundspeed/reanalysis.py to the repo root (four
# parents up from this file)
# once, so both paths below are absolute regardless of cwd (Task 14
# review, Important 3).
_REPO_ROOT = Path(__file__).resolve().parents[4]
#
# hycom_oregon_nov: OOI mooring site (44.37, -124.95) -- validation only, see
# the module docstring for why this must not be used as an experiment input.
HYCOM_PROFILE_PATH = _REPO_ROOT / "paper/results/hycom_profile_oregon_nov2021.csv"
# hycom_south_deep: South cable's own deepest channel -- the experiment profile.
HYCOM_EXPERIMENT_PROFILE_PATH = (
    _REPO_ROOT / "paper/results/hycom_profile_south_cable_deep.csv")

# South cable's deepest channel (from geometry.load_cables("fixtures")["South"],
# the row with the minimum `depth`, i.e. deepest below sea level): lat 45.1492,
# lon -125.1081, cable depth -1575 m. Chosen because it is the one point on
# either cable's geometry where local bathymetry is deep enough for a single
# HYCOM fetch to span (nearly) the full pick-depth range in one profile; every
# other along-cable point is shallower and would still need extrapolation for
# the deep picks. See the module docstring for the epistemic cost of this choice.
SOUTH_CABLE_DEEP_END = (45.1492, -125.1081)

# From the dataset's .das (confirmed live 2026-09-17): both water_temp and
# salinity are packed Int16 with these attributes. The NCSS "accept=csv"
# endpoint does not undo this packing itself.
HYCOM_FILL_RAW = -30000.0
HYCOM_SCALE = 0.001
HYCOM_OFFSET = 20.0

# Number of quadrature points used to sample the overlap band when comparing
# two profiles. Arbitrary but fine enough that `path_average`/`c_at`'s own
# linear interpolation dominates any error, not this grid.
_COMPARE_N_POINTS = 400

# Task 8's physical sanity gate (from_ts has no way to detect swapped T/S
# arguments itself): a real ocean sound speed is never outside this band. Any
# fetched profile failing this indicates a corrupted or misparsed response,
# not a subtle numerical issue, and must be reported rather than silently
# used.
SANE_C_MIN_MS = 1450.0
SANE_C_MAX_MS = 1550.0


def _find_col(columns, *needles: str) -> str:
    """First column whose lowercased name contains any of `needles`.

    HYCOM's NCSS CSV suffixes every column with its unit, e.g.
    `water_temp[unit="degC"]`, so exact-name matching would break on every
    dataset revision; substring matching on the variable name is what
    survives that.
    """
    for c in columns:
        cl = c.lower()
        if any(n in cl for n in needles):
            return c
    raise KeyError(f"no column matching {needles!r} in {list(columns)}")


def _unpack_hycom(raw: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Undo HYCOM's Int16 packing and flag which entries are the fill value.

    Returns (physical_values, valid_mask). Entries at the fill sentinel
    (-30000, e.g. below the local seafloor) get NaN in `physical_values` and
    False in `valid_mask` -- checked on the *raw* value, before scaling,
    since -30000 * 0.001 + 20.0 = -10.0 is itself a plausible-looking number
    and would silently corrupt a profile if checked after unpacking.
    """
    raw = np.asarray(raw, dtype=float)
    valid = ~np.isclose(raw, HYCOM_FILL_RAW) & ~np.isnan(raw)
    physical = np.where(valid, raw * HYCOM_SCALE + HYCOM_OFFSET, np.nan)
    return physical, valid


def fetch_hycom_profile(lat: float, lon: float, date: str, *, session=None,
                         timeout: int = 180) -> SoundSpeedProfile:
    """One full-depth T/S profile from HYCOM GOFS 3.1 at (lat, lon, date), as c(z).

    `session` is injectable (anything exposing `.get(url, params=..., timeout=...)`,
    e.g. `requests.Session()` or a test double) so the parse path -- column
    lookup, packed-value unpacking, fill/NaN dropping, depth ordering -- is
    exercised offline against a canned NCSS response, matching the pattern in
    `erddap.fetch_profile`. Defaults to the `requests` module itself.

    Rows at the fill sentinel (below the local seafloor at this grid point --
    e.g. the OOI mooring site is only ~600 m deep, far short of the cables'
    -1575 m) are dropped, not extrapolated.
    """
    params = {
        "var": "water_temp,salinity", "latitude": lat, "longitude": lon,
        "time": f"{date}T12:00:00Z", "vertCoordinate": "all",
        "accept": "csv", "addLatLon": "true",
    }
    get = (session or requests).get
    resp = get(HYCOM_NCSS, params=params, timeout=timeout)
    resp.raise_for_status()

    df = pd.read_csv(io.StringIO(resp.text))
    depth_col = _find_col(df.columns, "vertcoord", "depth")
    t_col = _find_col(df.columns, "water_temp")
    s_col = _find_col(df.columns, "salinity")

    depth = df[depth_col].to_numpy(dtype=float)
    t_phys, t_valid = _unpack_hycom(df[t_col].to_numpy(dtype=float))
    s_phys, s_valid = _unpack_hycom(df[s_col].to_numpy(dtype=float))

    n_raw = len(df)
    keep = t_valid & s_valid & ~np.isnan(depth)
    n_kept = int(keep.sum())
    if n_kept == 0:
        raise ValueError(
            f"hycom {lat:.2f},{lon:.2f} {date}: every one of {n_raw} rows was "
            f"the fill value or NaN -- likely a dry grid cell or bad request")

    z = depth[keep]
    t = t_phys[keep]
    s = s_phys[keep]
    order = np.argsort(z, kind="stable")
    z, t, s = z[order], t[order], s[order]
    # A single lat/lon/time NCSS point query should return each standard
    # depth level once, but guard against duplicates anyway: SoundSpeedProfile
    # requires z_down strictly ascending, and a repeated depth would raise
    # three modules away instead of here where the cause is obvious.
    z, first_idx = np.unique(z, return_index=True)
    t, s = t[first_idx], s[first_idx]

    pct = 100.0 * n_kept / n_raw if n_raw else 0.0
    source = (f"hycom:{date}:{lat:.2f},{lon:.2f}:"
              f"kept={n_kept}/{n_raw}({pct:.0f}%) z={z.min():.0f}..{z.max():.0f}m")
    return SoundSpeedProfile.from_ts(z, t, s, lat, lon, source=source)


def save_profile(profile: SoundSpeedProfile, path=HYCOM_PROFILE_PATH) -> Path:
    """Persist a fetched profile as a committed, network-free two-column CSV.

    This is how a live fetch becomes a reusable, reproducible experiment
    input rather than a network dependency at experiment time: fetch once
    (see `paper/scripts/validate_hycom_profile.py`), commit the file
    this writes, and `load_profile` reads it back exactly, with no network.

    `profile.source` is the only place `SoundSpeedProfile` carries
    provenance (product, date, lat/lon, kept/discarded counts), so it is
    written as a `#`-prefixed header line -- the same convention
    `experiments.runner.write_results` uses -- rather than lost the way a
    bare (z, c) array would lose it.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    with path.open("w", encoding="utf-8", newline="") as fh:
        fh.write(f"# source: {profile.source}\n# generated: {stamp}\n")
        pd.DataFrame({"z_down": profile.z_down, "c": profile.c}).to_csv(fh, index=False)
    return path


def load_profile(path=HYCOM_PROFILE_PATH) -> SoundSpeedProfile:
    """Load a profile written by `save_profile`. No network.

    Raises if the `# source:` provenance header is missing, rather than
    silently building a profile with no traceable origin.
    """
    path = Path(path)
    source = None
    with path.open("r", encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("# source:"):
                source = line[len("# source:"):].strip()
                break
    if source is None:
        raise ValueError(f"{path}: missing '# source:' provenance header")
    df = pd.read_csv(path, comment="#")
    return SoundSpeedProfile(df["z_down"].to_numpy(dtype=float),
                              df["c"].to_numpy(dtype=float), source)


def check_sound_speed_sanity(profile: SoundSpeedProfile,
                              lo: float = SANE_C_MIN_MS, hi: float = SANE_C_MAX_MS) -> None:
    """Raise if any sample in `profile` falls outside the physical sanity band.

    Task 8's gate: a real ocean sound speed is never outside ~1450-1550 m/s.
    Failing this means a corrupted fetch or a swapped temperature/salinity
    argument, not a subtle numerical issue -- a caller fetching a new profile
    (e.g. at a new location) must call this and report a failure loudly
    rather than silently accept whatever came back.
    """
    c = profile.c
    if c.min() < lo or c.max() > hi:
        raise ValueError(
            f"{profile.source}: sound speed {c.min():.1f}..{c.max():.1f} m/s "
            f"falls outside the sane band [{lo}, {hi}] m/s -- do not trust "
            f"this profile (likely a corrupted fetch or swapped T/S)")


def coverage_stats(profile: SoundSpeedProfile, depths) -> dict:
    """How much of `depths` (positive-down) falls inside `profile`'s sampled
    range vs. beyond its deepest sample, where `c_at`/`path_average` fall back
    to the clamped boundary speed instead of a real interpolated value.

    This is the mechanism behind the review finding that motivated
    `HYCOM_EXPERIMENT_PROFILE_PATH`: a profile that does not reach as deep as
    the data it will be used on produces correct-looking numbers that are
    actually all clamped extrapolation for every point beyond its range.
    `n`/`n_covered` state the denominator explicitly rather than reporting a
    bare percentage.
    """
    d = np.abs(np.asarray(depths, dtype=float))
    n = int(d.size)
    z_max = float(profile.z_down.max())
    covered = d <= z_max
    n_covered = int(covered.sum())
    beyond = d[~covered]
    return {
        "n": n,
        "n_covered": n_covered,
        "pct_covered": 100.0 * n_covered / n if n else 0.0,
        "profile_z_max_m": z_max,
        "max_extrapolation_m": float((beyond - z_max).max()) if beyond.size else 0.0,
    }


def compare_profiles(a: SoundSpeedProfile, b: SoundSpeedProfile,
                      z_lo: float, z_hi: float) -> pd.DataFrame:
    """Per-depth sound-speed difference over the overlapping band only.

    `[z_lo, z_hi]` is intersected with *both* profiles' own sampled extents,
    so a caller cannot accidentally compare a real measurement against a
    clamped extrapolation and call the agreement good. Callers should pass
    the actual fetched extent of whichever profile is the tighter one (e.g.
    the in-situ profile's own `z_down.min()/.max()`) rather than a literal
    depth, since the QC-passing in-situ band is window-dependent (see
    `erddap.NOV_2021_STATUS`) and hard-coding a number here would silently
    drift out of sync with whatever was actually fetched.
    """
    lo = max(float(z_lo), float(a.z_down.min()), float(b.z_down.min()))
    hi = min(float(z_hi), float(a.z_down.max()), float(b.z_down.max()))
    if hi <= lo:
        raise ValueError(
            f"profiles do not overlap in [{z_lo}, {z_hi}]: "
            f"{a.source} ({a.z_down.min()}..{a.z_down.max()}) vs "
            f"{b.source} ({b.z_down.min()}..{b.z_down.max()})")
    zz = np.linspace(lo, hi, _COMPARE_N_POINTS)
    return pd.DataFrame({"z_down": zz, "c_a": a.c_at(zz), "c_b": b.c_at(zz),
                          "diff_ms": a.c_at(zz) - b.c_at(zz)})


def validation_summary(df: pd.DataFrame) -> dict:
    """Summarise `compare_profiles`' output. Every field states its own `n`.

    This is the uncertainty on every downstream result over the band it was
    measured on -- it says nothing about the depths outside that band. For
    this research's OOI/HYCOM pairing, that excluded region is the entire
    upper water column above the validated band (roughly the top 150-575 m,
    window-dependent -- see `erddap.NOV_2021_STATUS`), which is exactly where
    every source sits and every ray passes. HYCOM there is unvalidated, not
    merely "assumed fine"; callers reporting a result must carry that caveat
    forward rather than let this summary's clean numbers imply full-depth
    agreement.
    """
    d = np.abs(df["diff_ms"].to_numpy(dtype=float))
    return {
        "n": int(d.size),
        "median_abs_diff_ms": float(np.median(d)),
        "p90_abs_diff_ms": float(np.percentile(d, 90)),
        "max_abs_diff_ms": float(d.max()),
    }
